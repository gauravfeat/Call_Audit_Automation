"""
Batch Audio Transcription CLI Script (Milestone 3).

Transcribes all standardized WAV recordings generated by Milestone 2.
Primary & Default STT Engine: Sarvam Saaras v4 (mode=codemix).
Optional Engine: Faster-Whisper (small / large-v3).

Features:
- Primary Sarvam Saaras v4 codemix pipeline
- Preserves Hindi-English code-mixing and domain financial vocabulary
- Automatic language detection (hi-IN, en-IN)
- Reuses existing valid outputs to prevent duplicate API charges
- Saves individual JSON transcripts in output/transcripts/sarvam_v4_codemix/
- Generates output/transcripts/sarvam_v4_codemix/transcription_summary.json
- Displays executive console summary table

Usage:
    python scripts/transcribe_audio.py
    python scripts/transcribe_audio.py --provider sarvam --mode codemix
    python scripts/transcribe_audio.py --provider whisper --model small
"""

import argparse
import json
import logging
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

# Ensure UTF-8 output on Windows console
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

# Ensure project root is in sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

# Load .env
from dotenv import load_dotenv
load_dotenv(PROJECT_ROOT / ".env")

from app.core.config import get_settings
from app.transcription.transcriber import AudioTranscriber, TranscriptionError

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("call_audit.cli.transcribe")


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    settings = get_settings()
    parser = argparse.ArgumentParser(
        description="Call Audit Automation - Primary Speech-to-Text Pipeline (Sarvam Saaras v4)",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--provider",
        type=str,
        default="sarvam",
        choices=["sarvam", "whisper", "whisper_api"],
        help="Speech-to-Text engine to use: 'sarvam', 'whisper', or 'whisper_api' (remote Whisper Large-v3).",
    )
    parser.add_argument(
        "--recording",
        type=str,
        default=None,
        help="Specific recording ID to transcribe (e.g. 'MOCK_CALL_002'). If omitted, processes all recordings.",
    )
    parser.add_argument(
        "--mode",
        type=str,
        default="codemix",
        choices=["codemix", "verbatim"],
        help="Transcription mode for Sarvam AI. Default is 'codemix'.",
    )
    parser.add_argument(
        "--input-dir",
        type=str,
        default=None,
        help="Directory containing standardized 16kHz WAV files (default: output/processed_audio)",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory to save JSON transcripts (default: output/transcripts/sarvam_v4_codemix)",
    )
    parser.add_argument(
        "--no-reuse",
        action="store_true",
        help="Force fresh transcription even if valid cached output exists.",
    )
    # Whisper-specific optional overrides
    parser.add_argument(
        "--model",
        type=str,
        default=None,
        help="Model identifier override (e.g., 'saaras:v4' or 'small')",
    )
    parser.add_argument(
        "--device",
        type=str,
        default=None,
        help="Inference device for Whisper: cpu or cuda",
    )
    parser.add_argument(
        "--beam-size",
        type=int,
        default=None,
        help="Beam search size for Whisper decoding",
    )
    return parser.parse_args()


def print_banner(provider: str, mode: str, model_id: str) -> None:
    """Print executive CLI header."""
    print("=" * 80)
    print("  CALL AUDIT AUTOMATION - PRIMARY SPEECH-TO-TEXT PIPELINE (M3)")
    print(f"  Provider: {provider.upper()} | Model: {model_id} | Mode: {mode.upper()}")
    print("=" * 80)


def print_summary(summary_data: Dict[str, Any]) -> None:
    """Print executive console summary table."""
    print("\n" + "=" * 80)
    print("  TRANSCRIPTION BATCH EXECUTION SUMMARY")
    print("=" * 80)
    print(f"  Primary STT Provider:            {summary_data.get('provider', 'sarvam').upper()}")
    print(f"  Model & Mode:                    {summary_data.get('model')} ({summary_data.get('mode')})")
    print(f"  Total recordings discovered:     {summary_data['total_recordings_discovered']}")
    print(f"  Successful transcriptions:       {summary_data['successful_transcriptions']}")
    print(f"  Failed transcriptions:           {summary_data['failed_transcriptions']}")
    print(f"  Total pipeline processing time:  {summary_data['total_processing_time']:.2f}s")
    if summary_data.get("total_api_cost_inr") is not None:
        print(f"  Total API Cost (INR):            ₹{summary_data['total_api_cost_inr']:.4f}")
    print("-" * 80)
    print(f"  Transcripts Directory:           {summary_data['output_directory']}")
    print(f"  Summary Report JSON:             {summary_data['summary_report_path']}")
    print("=" * 80)

    results = summary_data.get("results", [])
    if results:
        print("\nPer-Recording Breakdown:")
        print(f"  {'Filename':<40} {'Lang':<7} {'Words':<7} {'Duration':<9} {'Proc Time':<10} {'Cost (INR)':<11} {'Status'}")
        print("  " + "-" * 95)
        for r in results:
            fname = r["source_file"][:38]
            lang = r.get("detected_language", "N/A")
            words = f"{r.get('total_words', 0)}"
            dur = f"{r.get('audio_duration_seconds', 0):.1f}s" if "audio_duration_seconds" in r else "N/A"
            proc = f"{r.get('processing_time_seconds', 0):.1f}s" if "processing_time_seconds" in r else "N/A"
            cost = f"₹{r.get('api_cost_inr', 0.0):.4f}" if r.get("api_cost_inr") is not None else "₹0.0000"
            status = r["status"]
            print(f"  {fname:<40} {lang:<7} {words:<7} {dur:<9} {proc:<10} {cost:<11} {status}")
            if r.get("error"):
                print(f"    - [ERROR] {r['error']}")
            elif r.get("preview_text"):
                preview = r["preview_text"][:90] + ("..." if len(r["preview_text"]) > 90 else "")
                print(f"    - Preview: \"{preview}\"")
        print()


def main() -> int:
    """Main execution flow for batch transcription."""
    args = parse_args()
    settings = get_settings()

    provider = args.provider.lower()
    mode = args.mode.lower()
    reuse_existing = not args.no_reuse

    model_id = args.model or (settings.SARVAM_MODEL if provider == "sarvam" else settings.WHISPER_MODEL)
    print_banner(provider, mode, model_id)

    # Step 1: Discover processed WAV recordings
    input_dir = Path(args.input_dir).resolve() if args.input_dir else settings.processed_audio_dir

    if args.output_dir:
        output_dir = Path(args.output_dir).resolve()
    elif provider == "sarvam":
        output_dir = settings.primary_transcripts_dir
    elif provider in ("whisper_api", "remote_whisper"):
        output_dir = settings.onprem_whisper_transcripts_dir
    else:
        output_dir = settings.transcripts_dir

    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"\n[1/3] Discovering standardized audio files in: {input_dir}")
    if not input_dir.exists():
        print(f"[ERROR] Directory does not exist: {input_dir}", file=sys.stderr)
        print("Please run 'python scripts/process_audio.py' first to generate standardized WAV files.")
        return 1

    wav_files = sorted(list(input_dir.glob("*.wav")))
    if args.recording:
        target_stem = Path(args.recording).stem
        wav_files = [w for w in wav_files if w.stem == target_stem]
        if not wav_files:
            print(f"[ERROR] Specified recording '{args.recording}' not found in {input_dir}.", file=sys.stderr)
            return 1

    if not wav_files:
        print(f"[ERROR] No .wav files found in {input_dir}.", file=sys.stderr)
        print("Please run 'python scripts/process_audio.py' first to preprocess mock recordings.")
        return 1

    print(f"  Found {len(wav_files)} recording(s) to transcribe.")

    # Step 2: Initialize Transcriber
    print(f"\n[2/3] Initializing AudioTranscriber (provider='{provider}', mode='{mode}')...")
    if provider == "whisper":
        from app.transcription.model import WhisperModelManager
        device = (args.device or settings.WHISPER_DEVICE).lower()
        if args.beam_size is not None:
            settings.WHISPER_BEAM_SIZE = args.beam_size
        whisper_model = WhisperModelManager.get_model(
            model_size=model_id,
            device=device,
            compute_type=settings.WHISPER_COMPUTE_TYPE,
        )
        transcriber = AudioTranscriber(provider="whisper", model=whisper_model, settings=settings)
    elif provider in ("whisper_api", "remote_whisper"):
        transcriber = AudioTranscriber(provider="whisper_api", settings=settings)
    else:
        transcriber = AudioTranscriber(provider="sarvam", mode=mode, settings=settings)

    # Step 3: Sequential Transcription
    print(f"\n[3/3] Transcribing {len(wav_files)} recording(s)... (reuse_existing={reuse_existing})")

    results: List[Dict[str, Any]] = []
    detected_lang_map: Dict[str, str] = {}
    proc_time_map: Dict[str, float] = {}
    total_cost_inr = 0.0

    batch_start_time = time.perf_counter()

    for idx, wav_path in enumerate(wav_files, start=1):
        print(f"\n  [{idx}/{len(wav_files)}] Processing: {wav_path.name}")
        file_start = time.perf_counter()

        try:
            transcript = transcriber.transcribe_file(
                wav_path,
                reuse_existing=reuse_existing,
            )
            json_path = transcriber.save_transcript(transcript, output_dir=output_dir)

            file_elapsed = round(time.perf_counter() - file_start, 2)
            detected_lang_map[wav_path.name] = transcript.language
            proc_time_map[wav_path.name] = transcript.processing_time_seconds
            if transcript.api_cost_inr:
                total_cost_inr += transcript.api_cost_inr

            preview = transcript.full_text[:120] if transcript.full_text else "[No speech detected]"

            results.append(
                {
                    "recording_id": transcript.recording_id,
                    "source_file": wav_path.name,
                    "status": "SUCCESS",
                    "provider": transcript.provider,
                    "model": transcript.model,
                    "transcription_mode": transcript.transcription_mode,
                    "detected_language": transcript.language,
                    "language_probability": transcript.language_probability,
                    "audio_duration_seconds": transcript.duration,
                    "processing_time_seconds": transcript.processing_time_seconds,
                    "api_cost_inr": transcript.api_cost_inr,
                    "total_segments": len(transcript.segments),
                    "total_words": transcript.total_words,
                    "transcript_json": str(json_path),
                    "preview_text": preview,
                }
            )
            cost_str = f", cost=INR {transcript.api_cost_inr:.4f}" if transcript.api_cost_inr else ""
            print(f"      Status: SUCCESS (lang={transcript.language}, words={transcript.total_words}, time={transcript.processing_time_seconds:.1f}s{cost_str})")

        except (TranscriptionError, Exception) as exc:
            file_elapsed = round(time.perf_counter() - file_start, 2)
            proc_time_map[wav_path.name] = file_elapsed
            err_msg = str(exc)
            logger.error("Failed to transcribe %s: %s", wav_path.name, err_msg)

            results.append(
                {
                    "recording_id": wav_path.stem,
                    "source_file": wav_path.name,
                    "status": "FAILED",
                    "provider": provider,
                    "processing_time_seconds": file_elapsed,
                    "error": err_msg,
                }
            )
            print(f"      Status: FAILED ({err_msg})")

    total_batch_time = round(time.perf_counter() - batch_start_time, 2)

    # Step 4: Construct and Save Summary Report
    successful_count = sum(1 for r in results if r["status"] == "SUCCESS")
    failed_count = sum(1 for r in results if r["status"] == "FAILED")

    summary_path = output_dir / "transcription_summary.json"
    summary_data = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "provider": provider,
        "model": model_id,
        "mode": mode,
        "total_recordings_discovered": len(wav_files),
        "successful_transcriptions": successful_count,
        "failed_transcriptions": failed_count,
        "total_processing_time": total_batch_time,
        "total_api_cost_inr": round(total_cost_inr, 4) if provider == "sarvam" else None,
        "output_directory": str(output_dir),
        "summary_report_path": str(summary_path),
        "detected_language_per_recording": detected_lang_map,
        "processing_duration_per_recording": proc_time_map,
        "results": results,
    }

    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary_data, f, indent=2, ensure_ascii=False)

    logger.info("Saved transcription summary to: %s", summary_path)

    # Step 5: Display Executive Summary
    print_summary(summary_data)

    if failed_count > 0 and successful_count == 0:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
